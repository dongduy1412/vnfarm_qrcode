"""Generate public trust anchors for common Worker/custom-domain TLS chains.
Run explicitly when refreshing trust roots; never downloads unverified certificates.
"""
from pathlib import Path
import certifi
from cryptography import x509
from cryptography.hazmat.primitives.serialization import Encoding

roots = x509.load_pem_x509_certificates(Path(certifi.where()).read_bytes())
selected = [c for c in roots if any(name in c.subject.rfc4514_string()
            for name in ('GTS Root', 'ISRG Root', 'GlobalSign'))]
assert selected
pem = ''.join(c.public_bytes(Encoding.PEM).decode() for c in selected)
path = Path(__file__).resolve().parents[1] / 'include/WorkerRootCAs.h'
path.write_text('#pragma once\n// Public roots from certifi: GTS, ISRG, GlobalSign.\n'
                '// Generated by tools/generate_worker_ca.py; no private material.\n'
                'static const char WORKER_ROOT_CAS[] = R"PEM(' + pem + ')PEM";\n', encoding='utf-8')
print('Generated public roots:', len(selected))
